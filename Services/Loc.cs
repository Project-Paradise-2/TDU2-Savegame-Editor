using System.Globalization;

namespace TDU2SaveEditor.Services;

/// <summary>
/// Tiny localization helper. The UI language is detected from the current UI
/// culture (German -> DE) and anything else falls back to English. The user can
/// switch at runtime; <see cref="LanguageChanged"/> lets the UI refresh.
/// </summary>
public static class Loc
{
    public enum Lang { DE, EN }

    public static Lang Current { get; private set; } = Detect();
    public static event Action? LanguageChanged;

    public static bool IsGerman => Current == Lang.DE;

    public static Lang Detect()
    {
        try
        {
            return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "de" ? Lang.DE : Lang.EN;
        }
        catch
        {
            return Lang.EN;
        }
    }

    public static void Set(Lang lang)
    {
        if (lang == Current) return;
        Current = lang;
        LanguageChanged?.Invoke();
    }

    public static string T(string key)
    {
        var table = Current == Lang.DE ? De : En;
        return table.TryGetValue(key, out var v) ? v : key;
    }

    public static string F(string key, params object[] args)
        => string.Format(CultureInfo.InvariantCulture, T(key), args);

    /// <summary>
    /// Finds the key whose value equals <paramref name="text"/> in either
    /// language table. Used to localize existing XAML text at runtime.
    /// </summary>
    public static string? KeyFor(string? text)
    {
        if (string.IsNullOrEmpty(text)) return null;
        foreach (var table in new[] { De, En })
            foreach (var kv in table)
                if (kv.Value == text)
                    return kv.Key;
        return null;
    }

